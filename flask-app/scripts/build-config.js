// Generates config.js from environment variables.
// Runs both locally (reads .env) and on Netlify (reads build env vars).
//
// Usage: node scripts/build-config.js
//
// It writes window.APP_CONFIG into ./config.js, which index.html loads before
// the app scripts. The Supabase URL + anon key are public by design; data is
// protected by Row Level Security, not by hiding the key.

const fs = require("fs");
const path = require("path");

// Lightweight .env loader (no dependency). Only used locally; on Netlify the
// vars already live in process.env so a missing .env is fine.
function loadDotEnv() {
  const envPath = path.join(__dirname, "..", ".env");
  if (!fs.existsSync(envPath)) return;
  const text = fs.readFileSync(envPath, "utf8");
  for (const rawLine of text.split("\n")) {
    const line = rawLine.trim();
    if (!line || line.startsWith("#")) continue;
    const eq = line.indexOf("=");
    if (eq === -1) continue;
    const key = line.slice(0, eq).trim();
    let value = line.slice(eq + 1).trim();
    // strip surrounding quotes if present
    if ((value.startsWith('"') && value.endsWith('"')) ||
        (value.startsWith("'") && value.endsWith("'"))) {
      value = value.slice(1, -1);
    }
    if (!(key in process.env)) process.env[key] = value;
  }
}

loadDotEnv();

const url = process.env.SUPABASE_URL;
const anonKey = process.env.SUPABASE_ANON_KEY;

if (!url || !anonKey) {
  console.error(
    "\n[build-config] Missing SUPABASE_URL or SUPABASE_ANON_KEY.\n" +
    "  Local:   copy .env.example to .env and fill in your values.\n" +
    "  Netlify: set them under Site settings → Environment variables.\n"
  );
  process.exit(1);
}

const out =
`// AUTO-GENERATED by scripts/build-config.js — do not edit, do not commit.
window.APP_CONFIG = {
  SUPABASE_URL: ${JSON.stringify(url)},
  SUPABASE_ANON_KEY: ${JSON.stringify(anonKey)},
};
`;

fs.writeFileSync(path.join(__dirname, "..", "config.js"), out);
console.log("[build-config] Wrote config.js");
